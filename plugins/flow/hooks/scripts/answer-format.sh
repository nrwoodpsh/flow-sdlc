#!/bin/bash
# 답변 형식 주입 — 플러그인을 설치하면 어느 프로젝트에서든 답변 출력이 통일된다.
#
# CLAUDE.md 가 아니라 훅인 이유: 템플릿 CLAUDE.md 는 /flow:setup 을 돌린 프로젝트에만
# 닿는다. 설치 즉시 적용되는 층은 SessionStart additionalContext 뿐이다 (실측 검증된 기제).
# 검사 훅(check-*)과 달리 조용할 조건이 없다 — 항상 주입하고, 비용은 세션당 한 번이다.
#
# 형식 자체는 사용자가 확정했다 (doc/95.대화.md R10~R12) — 이해 부채 처방:
# 훑는 위치가 항상 같으면 흡수가 빨라진다. 칸 이름은 일상어다(결론·선례·연결·약점) —
# 어려운 용어(판정·계보·흠)는 사용자 피드백으로 기각됐다. 따옴표(")를 넣지 마라 — JSON 이 깨진다.

ctx="[flow 답변 형식] 판단·검토 답변은 이 순서로, 칸마다 제목 줄을 달고 내용은 목록과 줄바꿈으로 훑기 좋게 쓴다: 결론(한 줄, 항상 먼저) → 선례(이미 검증된 방법인가) → 연결(기존 결정과 어떻게 맞물리나) → 약점(정직하게 — 못 찾았으면 '못 찾았다'고 명시, 이 칸만 침묵 금지) → 다음 질문(문답 중일 때만). 사실·상태 보고는 6하 중 있는 것만 2열 표(항목 | 내용)로 쓴다 — 항목 이름은 질문 단어가 아니라 내용어로(담당·대상·방법·시점·위치·이유), 한 칸은 짧게. 없는 칸은 통째로 생략한다 — 억지로 채우지 않는다. 쉬운 일상어를 쓴다. 판단도 사실 보고도 아닌 질문(절차 안내·코드·탐색 대화)에는 형식을 강요하지 않고, 복합 질문은 갈래별로 나눠 각 형식으로 답한다. 틀에 안 들어가는 내용은 버리지 말고 마지막에 '틀 밖' 절로 덧붙인다. 별도 출력 형식이 정해진 산출물(커맨드 리포트·문서 템플릿)은 그 형식이 우선한다."
printf '{"hookSpecificOutput":{"hookEventName":"SessionStart","additionalContext":"%s"}}\n' "$ctx"
exit 0
